/* Э6: чёткие буквы шрифтов. Чистая часть (fontpages_core.c) — без Direct3D, тестируется отдельно
 * (tests/test_fontpages.c); в игре — fontpages.c.
 *
 * Опора — как игра рисует буквы:
 *  - страница шрифта — BMFont, BGRA8 без mip, буквы по каналам B/G/R/A; заливка при первом использовании:
 *    UpdateSubresource в промежуточную текстуру -> CopyResource в рабочую (SRV);
 *  - буква (eFontBMF, слот 12 0x630da0): прямоугольник ровно в её ячейку ×1, место = перо + кернинг + смещение глифа,
 *    всё в целых логических пикселях; обрезка рамкой (param_6) — та же сторона с пересчитанным UV (0x631d30);
 *  - вершина 36 байт: x, y, z (float) | 12 байт | маска канала (4 байта) | u, v (float, доли страницы); на букву 4
 *    вершины, между буквами 2 повторённые: полоса треугольников, n = 6 * букв - 2; рисование — Draw из общего буфера
 *    вершин (UpdateSubresource с областью; проверено в игре 19.11);
 *  - TextPS: a = dot(страница(u, v), маска) — канал выбирает маска вершины; нулевая маска — цветной значок как есть;
 *  - отпечаток страницы — FNV-1a 64 по каждому 97-му байту плотных строк BGRA (как у трассировщика реверса); при
 *    совпадении — ещё CRC32 всех байт (ревизия v3, п. 5: страница, изменённая другим модом, не примется за свою).
 * Ячейки BMFont обрезаны вплотную по букве ×1, та же буква ×K шире и выше —
 * в ячейке ×1 она срезается (краткая «й», точки, дефисы). Поэтому у каждой своей буквы — своя ячейка: картинка ×K
 * целиком, на месте буквы игры (база ×K, центр по букве игры), из маленькой своей страницы («атласа») — в том же канале,
 * что и на странице игры, поэтому маска вершины выбирает её без изменений.
 *
 * Файл ui4k_fonts<K>.dat (little-endian):
 *   "U4KF", u32 версия = 3 (2 — без CRC32, тоже читается), u32 K, u32 число страниц;
 *   страницы (32 байта; у версии 2 — 24, без двух последних полей): u32 ширина, u32 высота, u64 отпечаток, u32 число
 *          букв, u32 смещение первой буквы от начала файла, u32 CRC32 всех байт страницы (плотные строки BGRA), u32 0;
 *   буква (18 байт): u16 x, y, w, h (ячейка на странице игры), u8 канал (байт BGRA 0..3), u8 0, i16 ox, oy (левый верхний
 *          угол картинки от угла ячейки, пиксели ×K), u16 iw, ih (её размер ×K), затем iw*ih байт яркости, строки сверху
 *          вниз; запись дополнена нулями до кратного 4. */
#pragma once
#include <stddef.h>
#include <stdint.h>

#define FP_MAX_PAGES 4096
#define FP_VSTRIDE 36            /* вершина текста: шаг */
#define FP_VCOLOR 24             /* маска канала */
#define FP_VUV 28                /* u, v */
#define FP_OVERHANG 32           /* картинка дальше от ячейки (логических px) — порча образца, буква остаётся игре.
                                  * (Апостроф на некоторых страницах игры — пустая ячейка: игра его не рисует, и мод тоже —
                                  * запись пустая, 19.11) */
#define FP_GAP 2                 /* поля между буквами атласа (и от его края): линейная выборка не цепляет соседей */

typedef struct {
    uint16_t x, y, w, h;   /* ячейка на странице игры, логические тексели */
    uint8_t chan;          /* байт BGRA */
    int16_t ox, oy;        /* угол картинки от угла ячейки, пиксели ×K */
    uint16_t iw, ih;       /* картинка ×K */
    const uint8_t *px;
} FpGlyph;

typedef struct {
    uint32_t w, h;
    uint64_t hash;
    uint32_t n;
    FpGlyph *g;
    uint32_t crc;          /* CRC32 всех байт страницы (версия 3) */
    int has_crc;
} FpPage;

typedef struct {
    uint32_t K, npages;
    FpPage *pages;
    FpGlyph *glyphs;
} FpData;

int fp_parse(const uint8_t *file, size_t n, FpData *out);
void fp_free(FpData *d);
const FpPage *fp_find(const FpData *d, uint32_t w, uint32_t h, uint64_t hash);
uint32_t fp_crc32(const uint8_t *data, uint32_t w, uint32_t h, uint32_t rp);   /* плотные строки w*4 байт */
uint64_t fp_hash97(const uint8_t *data, uint32_t w, uint32_t h, uint32_t rp);

/* ---- атлас: свои буквы страницы для масштаба q = num/den (физических px на логический) ---- */
enum { FP_NOT_OWN = 0, FP_OWN = 1, FP_BLANK = 2 };
typedef struct {
    int32_t X0, Y0, X1, Y1;     /* картинка в физических px от угла ячейки */
    uint32_t ax, ay;            /* её левый верхний угол в атласе */
    int32_t kind;               /* FP_OWN; FP_BLANK — знак пуст и при ×K (пробел: ячейка игры тоже пуста — не рисовать);
                                 * FP_NOT_OWN — остаётся странице игры */
} FpPlace;

typedef struct {
    uint32_t K, num, den;       /* образец ×K, масштаб num/den */
    uint32_t AW, AH;            /* размер атласа */
    uint32_t n, own;            /* мест (= pg->n), из них своих букв */
    FpPlace *pl;
    const FpPage *pg;
} FpAtlas;

/* Раскладка: картинка каждой буквы в физическом размере, четыре канала укладываются независимо (полками).
 * q == K — картинка как есть; иначе — среднее образца ×K по площади физического пикселя, сетка — от угла ячейки.
 * 1 — ок (освободить fp_atlas_free). */
int fp_atlas_layout(const FpPage *pg, uint32_t K, uint32_t num, uint32_t den, FpAtlas *at);
void fp_atlas_free(FpAtlas *at);
/* картинка буквы i в физическом размере: out — (X1-X0)*(Y1-Y0) байт; tmp — ih*(X1-X0) float */
void fp_glyph_phys(const FpAtlas *at, uint32_t i, uint8_t *out, float *tmp);
/* весь атлас: BGRA AW*AH, буквы в своих каналах. 1 — ок */
int fp_atlas_pixels(const FpAtlas *at, uint8_t *out);

/* ---- рисование текста: вершины игры -> свои ячейки ---- */
typedef struct { double rx, bx, ry, by; } FpMap;   /* физический px цели = r * логическая координата вершины + b */
typedef struct { uint32_t own, other, dropped; } FpCount;   /* dropped — пустые и обрезанные целиком */

/* Полоса букв игры in (n вершин) с этой страницы:
 *  - свои буквы -> own (полоса, *no вершин): ячейка = картинка буквы целиком, угол ячейки игры прижат к целому
 *    физическому px (при q == K он и так целый), UV — в атласе; рамка обрезки игры — та же (её края видны по буквам,
 *    которые игра обрезала);
 *  - пустые знаки (FP_BLANK) не рисуются;
 *  - остальные знаки (другие языки, значки, растянутые) -> oth (*nt вершин) без изменений — рисуются страницей игры.
 * own и oth — не меньше n вершин каждый. mode — чем маска вершины выбирает канал: -1 не известно (решается по
 * совпадению ячеек и запоминается), 0 — байт маски = байт страницы, 1 — байты 0 и 2 переставлены.
 * 1 — есть свои буквы; 0 — рисовать как есть (не полоса букв или своих нет). */
int fp_rewrite(const FpAtlas *at, const FpMap *m, int *mode, const uint8_t *in, uint32_t n, uint8_t *own, uint32_t *no,
               uint8_t *oth, uint32_t *nt, FpCount *cnt);
